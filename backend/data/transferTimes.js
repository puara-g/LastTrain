// 지선(예: "6호선 응암순환(단방향)")도 원본 데이터 기준으로는 그냥 "6호선"이므로
// 본선 이름만 떼어서 비교한다.
function baseLine(line) {
  return line.split(" ")[0];
}

function getTransferMinutes(stationName, lineA, lineB) {
  const table = TRANSFER_MINUTES[stationName];
  if (!table) return DEFAULT_TRANSFER_MINUTES;

  if (lineA && lineB) {
    const key = [baseLine(lineA), baseLine(lineB)].sort().join("|");
    if (table[key] != null) return table[key];
  }

  // 정확한 노선 조합을 못 찾으면(예: 데이터에 없는 조합), 그 역의 알려진 값 중
  // 가장 흔한(중앙값) 값으로 근사한다 — 완전 기본값(5분)보다는 그 역 사정에 가깝다.
  const known = Object.values(table).sort((a, b) => a - b);
  return known[Math.floor(known.length / 2)];
}

module.exports = { getTransferMinutes, DEFAULT_TRANSFER_MINUTES, TRANSFER_MINUTES };
